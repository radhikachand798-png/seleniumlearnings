package operators;

public class RelationalOperator {
    public static void main(String [] args) {

        int numberOne = 5;
        int numberTwo = 10;
        System.out.println(numberOne == numberTwo);
        System.out.println(numberOne != numberTwo);
        System.out.println(numberOne > numberTwo);
        System.out.println(numberOne < numberTwo);
        System.out.println(numberOne >= numberTwo);
        System.out.println(numberOne <= numberTwo);
    }
}
